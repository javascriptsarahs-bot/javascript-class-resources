/*
JavaScript Numbers

Unlike Java or C, JavaScript does not have separate
number types such as int, long, float, and double.

JavaScript traditionally uses one main numeric type:
Number

Examples:
10       → Number
3.14     → Number
-5       → Number
100.0    → Number

In JavaScript, both integers and decimal numbers
are represented using the Number type.

There is no separate data type specifically for integers.
*/


// All of these are the Number type in JavaScript.

var integer = 10;      // Integer
var decimal = 10.12;   // Decimal (floating-point number)
var negative = -20;    // Negative integer


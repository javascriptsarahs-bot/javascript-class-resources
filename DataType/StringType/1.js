/*
String Type

Strings are used to represent text data.

In JavaScript, we can create a string by wrapping text with:
- single quotes: 'Hello'
- double quotes: "Hello"
- backticks: `Hello`

Single quotes are commonly used, but there is no single rule
that says you must use one type of quotation mark.

In a company or team, developers usually follow the same coding convention.
This makes the code consistent and easier to read and share with others.
*/

console.log('Hello');
console.log("Hello");
console.log(`Hello`);


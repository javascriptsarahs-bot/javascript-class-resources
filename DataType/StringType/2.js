/*
Quotes inside a String

1. If a string is wrapped with single quotes (' '),
   you can use double quotes (" ") inside the string.

2. If a string is wrapped with double quotes (" "),
   you can use single quotes (' ') inside the string.

3. If a string is wrapped with backticks (` `),
   you can use both single and double quotes inside the string.
*/

var string;

string = 'He said, "Hello!"';
console.log(string); // ? 

string = "It's a beautiful day.";
console.log(string); // ? 

string = `He said, "It's a beautiful day."`;
console.log(string); // ? 


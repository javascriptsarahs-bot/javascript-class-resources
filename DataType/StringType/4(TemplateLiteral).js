/*
Template Literals

Starting with ES6 (ECMAScript 2015), JavaScript introduced
a new way to write strings called template literals.

Regular strings use:
- Single quotes: ' '
- Double quotes: " "

Template literals use:
- Backticks: ` `

Examples:
*/

var string1 = 'Hello';
var string2 = "Hello";
var string3 = `Hello`;


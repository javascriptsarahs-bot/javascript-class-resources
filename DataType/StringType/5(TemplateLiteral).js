/*
Multi-line Strings

A multi-line string is a string that is written
across multiple lines.

With regular strings, we can use \n to create
a new line.

\n means "new line."
*/

var message = 'Hello!\nHow are you?\nNice to meet you.';

// Guess the output before running this code in the terminal!

console.log(message);
console.log("----------------------");

/*
Multi-line Strings with Template Literals

With a template literal, we do not need to use \n.

We can simply write the string across multiple lines
inside the backticks.

The line breaks inside the backticks become part
of the string.
*/

var message = `Hello!
How are you?
Nice to meet you.`;

// Guess the output before running this code in the terminal!

console.log(message);

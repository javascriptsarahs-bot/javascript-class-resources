/*
Expressions inside ${ }

We can also put an expression inside ${ }.

An expression is code that produces a value.

For example:

10 + 20

produces the value 30.
*/

var a = 10;
var b = 20;

// Guess the output before running this code in the terminal!

console.log(`The answer is ${a + b}.`);  // ?
console.log(`The answer is ${a * b}.`);  // ?